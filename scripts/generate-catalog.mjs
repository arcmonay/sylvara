for (const p of products) {
  if (p.plants.includes("tomato") || p.searchTerms.includes("tomato") || p.handle.includes("tomato")) {
    p.relatedHandles = tomatoRelated.filter((h) => h !== p.handle).slice(0, 6);
  } else if (!p.relatedHandles.length) {
    p.relatedHandles = products
      .filter((x) => x.collection === p.collection && x.handle !== p.handle)
      .slice(0, 4)
      .map((x) => x.handle);
  }
  if (!p.completeTheSystem.length) {
    p.completeTheSystem = p.relatedHandles.slice(0, 3);
  }
}

